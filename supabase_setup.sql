-- سجل الوجبات المشترك لمفقس خيرات أربيل
create table if not exists public.batch_register (
  id bigint generated by default as identity primary key,
  batch_number text not null,
  input_date date not null,
  transfer_date date,
  cartons integer not null default 0 check (cartons >= 0),
  output_date date,
  notes text,
  created_at timestamptz not null default now()
);

alter table public.batch_register enable row level security;

-- سجل مفتوح بدون تسجيل دخول: كل زائر يستطيع القراءة والإضافة والتعديل والحذف.
-- هذا مناسب فقط إذا كنت موافقاً أن أي شخص لديه الرابط يمكنه تغيير البيانات.
drop policy if exists "public read batch register" on public.batch_register;
drop policy if exists "public insert batch register" on public.batch_register;
drop policy if exists "public update batch register" on public.batch_register;
drop policy if exists "public delete batch register" on public.batch_register;
create policy "public read batch register" on public.batch_register for select to anon, authenticated using (true);
create policy "public insert batch register" on public.batch_register for insert to anon, authenticated with check (true);
create policy "public update batch register" on public.batch_register for update to anon, authenticated using (true) with check (true);
create policy "public delete batch register" on public.batch_register for delete to anon, authenticated using (true);
